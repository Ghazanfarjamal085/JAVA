public class Nested_loop {
        public static void main(String[] args) {
        int i = 1;
        while (i <= 5) {
            System.out.println("jamal" + " " + i);
            int j = 1;
            while (j <= 3) {
                System.out.println("Hello");
                j++;
            }
            i++;
        }
    }
}
